package org.wildfly.feature.pack.grpc.test.security;

import java.io.InputStream;
import java.security.KeyStore;
import java.util.concurrent.TimeUnit;

import javax.net.ssl.KeyManagerFactory;

import org.jboss.arquillian.container.test.api.Deployment;
import org.jboss.arquillian.container.test.api.RunAsClient;
import org.jboss.arquillian.junit.Arquillian;
import org.jboss.as.arquillian.api.ServerSetup;
import org.jboss.as.arquillian.container.ManagementClient;
import org.jboss.as.arquillian.setup.SnapshotServerSetupTask;
import org.jboss.as.controller.client.helpers.Operations;
import org.jboss.as.controller.client.helpers.Operations.CompositeOperationBuilder;
import org.jboss.dmr.ModelNode;
import org.jboss.shrinkwrap.api.Archive;
import org.jboss.shrinkwrap.api.ShrinkWrap;
import org.jboss.shrinkwrap.api.spec.WebArchive;
import org.junit.AfterClass;
import org.junit.Assert;
import org.junit.BeforeClass;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.wildfly.feature.pack.grpc.test.helloworld.GreeterGrpc;
import org.wildfly.feature.pack.grpc.test.helloworld.TwowaySecureHelloWorldTest;
import org.wildfly.feature.pack.grpc.test.utility.ServerReload;

import io.grpc.ChannelCredentials;
import io.grpc.Grpc;
import io.grpc.ManagedChannel;
import io.grpc.TlsChannelCredentials;
import messages.HelloReply;
import messages.HelloRequest;

/**
 * Verifies that mutual TLS (mTLS), combined with a properly configured Elytron
 * security domain and {@code http-authentication-factory} on the gRPC subsystem,
 * propagates the client certificate's identity into the gRPC
 * {@link io.grpc.Context} via {@link org.wildfly.extension.grpc.GrpcSecurity#SECURITY_IDENTITY_KEY}.
 *
 * <p>The ssl-gen module generates client certificates with {@code CN=client}.
 * The test configures an Elytron {@code filesystem-realm} with that identity,
 * an {@code x500-attribute-principal-decoder} to extract {@code CN} from the
 * certificate subject, and an {@code http-authentication-factory} wired into
 * {@code /subsystem=grpc}. The built-in interceptor then authenticates the
 * client certificate from the SSL session and exposes the identity so that
 * gRPC service methods can read it via {@code SECURITY_IDENTITY_KEY.get()}.
 */
@RunWith(Arquillian.class)
@ServerSetup({
    TwowaySecureHelloWorldTest.MutualTlsServerSetupTask.class,
    MutualTlsElytronSecurityIdentityTest.ElytronMutualTlsSetupTask.class
})
@RunAsClient
public class MutualTlsElytronSecurityIdentityTest {

    private static final String TARGET_HOST = "127.0.0.1";
    private static final int SECURE_PORT = 8443;

    // Client certificate CN as generated by the ssl-gen module
    static final String CLIENT_CERT_CN = "client";

    static final String REALM_NAME = "grpc-mtls-realm";
    static final String DECODER_NAME = "grpc-cn-decoder";
    static final String DOMAIN_NAME = "grpc-mtls-domain";
    static final String HTTP_AUTH_FACTORY_NAME = "grpc-mtls-http-auth";

    private static ManagedChannel channel;
    private static GreeterGrpc.GreeterBlockingStub blockingStub;

    // -------------------------------------------------------------------------
    // Server setup: Elytron realm + security domain + http-authentication-factory
    // -------------------------------------------------------------------------

    /**
     * Configures Elytron for certificate-based authentication and wires the
     * {@code http-authentication-factory} into the gRPC subsystem.
     * Runs AFTER {@link TwowaySecureHelloWorldTest.MutualTlsServerSetupTask},
     * which enables {@code need-client-auth=true} on the HTTPS listener.
     */
    public static class ElytronMutualTlsSetupTask extends SnapshotServerSetupTask {

        @Override
        protected void doSetup(ManagementClient client, String containerId) throws Exception {
            final ModelNode realmAddress = Operations.createAddress(
                    "subsystem", "elytron", "filesystem-realm", REALM_NAME);

            final CompositeOperationBuilder builder = CompositeOperationBuilder.create();

            // 1. filesystem-realm to hold the client identity
            ModelNode op = Operations.createAddOperation(realmAddress);
            op.get("path").set(REALM_NAME);
            op.get("relative-to").set("jboss.server.data.dir");
            builder.addStep(op);

            // 2. x500-attribute-principal-decoder: extracts CN from the X.500 subject
            ModelNode decoderAddress = Operations.createAddress(
                    "subsystem", "elytron", "x500-attribute-principal-decoder", DECODER_NAME);
            op = Operations.createAddOperation(decoderAddress);
            op.get("attribute-name").set("CN");
            builder.addStep(op);

            // 3. security-domain using the realm and the CN decoder
            ModelNode domainAddress = Operations.createAddress(
                    "subsystem", "elytron", "security-domain", DOMAIN_NAME);
            op = Operations.createAddOperation(domainAddress);
            op.get("default-realm").set(REALM_NAME);
            op.get("permission-mapper").set("default-permission-mapper");
            op.get("principal-decoder").set(DECODER_NAME);
            op.get("realms").add().get("realm").set(REALM_NAME);
            builder.addStep(op);

            // 4. http-authentication-factory with CLIENT_CERT mechanism
            ModelNode factoryAddress = Operations.createAddress(
                    "subsystem", "elytron", "http-authentication-factory", HTTP_AUTH_FACTORY_NAME);
            op = Operations.createAddOperation(factoryAddress);
            op.get("http-server-mechanism-factory").set("global");
            op.get("security-domain").set(DOMAIN_NAME);
            op.get("mechanism-configurations").add()
                    .get("mechanism-name").set("CLIENT_CERT");
            builder.addStep(op);

            // 5. Wire the http-authentication-factory into the gRPC subsystem
            builder.addStep(Operations.createWriteAttributeOperation(
                    Operations.createAddress("subsystem", "grpc"),
                    "http-authentication-factory",
                    new ModelNode(HTTP_AUTH_FACTORY_NAME)));

            ModelNode compositeResult = client.getControllerClient().execute(builder.build());
            if (!Operations.isSuccessfulOutcome(compositeResult)) {
                throw new RuntimeException("Failed to set up mTLS Elytron config: "
                        + Operations.getFailureDescription(compositeResult));
            }

            // 6. Add the client identity (CN=client) to the realm
            ModelNode removeOp = Operations.createOperation("remove-identity", realmAddress);
            removeOp.get("identity").set(CLIENT_CERT_CN);
            client.getControllerClient().execute(removeOp); // ignore outcome

            ModelNode addOp = Operations.createOperation("add-identity", realmAddress);
            addOp.get("identity").set(CLIENT_CERT_CN);
            ModelNode addResult = client.getControllerClient().execute(addOp);
            if (!Operations.isSuccessfulOutcome(addResult)) {
                throw new RuntimeException("Failed to add identity: "
                        + Operations.getFailureDescription(addResult));
            }

            ServerReload.executeReloadAndWaitForCompletion(client.getControllerClient());
        }
    }

    // -------------------------------------------------------------------------
    // Deployment
    // -------------------------------------------------------------------------

    @Deployment
    public static Archive<?> createTestArchive() {
        WebArchive war = ShrinkWrap.create(WebArchive.class, "MutualTlsElytronSecurityIdentityTest.war");
        war.addClasses(SecurityIdentityGreeterServiceImpl.class);
        war.addPackage(HelloRequest.class.getPackage());
        war.addClass(GreeterGrpc.class);
        return war;
    }

    // -------------------------------------------------------------------------
    // Channel lifecycle: mTLS (same as TwowaySecureHelloWorldTest)
    // -------------------------------------------------------------------------

    @BeforeClass
    public static void beforeClass() throws Exception {
        ClassLoader classLoader = MutualTlsElytronSecurityIdentityTest.class.getClassLoader();

        KeyStore clientKeyStore = KeyStore.getInstance("PKCS12");
        try (InputStream clientKeyStoreStream = classLoader.getResourceAsStream("client.keystore.p12")) {
            clientKeyStore.load(clientKeyStoreStream, "secret".toCharArray());
        }
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(clientKeyStore, "secret".toCharArray());

        try (InputStream trustStore = classLoader.getResourceAsStream("client.truststore.pem")) {
            ChannelCredentials creds = TlsChannelCredentials.newBuilder()
                    .trustManager(trustStore)
                    .keyManager(kmf.getKeyManagers())
                    .build();
            channel = Grpc.newChannelBuilderForAddress(TARGET_HOST, SECURE_PORT, creds).build();
        }
        blockingStub = GreeterGrpc.newBlockingStub(channel);
    }

    @AfterClass
    public static void afterClass() throws Exception {
        if (channel != null) {
            channel.shutdownNow().awaitTermination(5, TimeUnit.SECONDS);
        }
    }

    // -------------------------------------------------------------------------
    // Tests
    // -------------------------------------------------------------------------

    /**
     * Verifies that when mutual TLS is configured together with an Elytron
     * {@code http-authentication-factory} on the gRPC subsystem, the client
     * certificate's CN ({@code "client"}) is available as the security identity
     * principal via {@link org.wildfly.extension.grpc.GrpcSecurity#SECURITY_IDENTITY_KEY}.
     */
    @Test
    public void securityIdentityIsPopulatedFromClientCertificate() {
        HelloReply reply = blockingStub.sayHello(HelloRequest.newBuilder().setName("test").build());
        Assert.assertEquals(
                "The gRPC service must see the client certificate's CN as the security identity principal",
                CLIENT_CERT_CN, reply.getMessage());
    }
}
